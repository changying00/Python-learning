"""
参数传递

    # 值传递  :   不可变类型 采用 值传递。
    #
    # 引用传递 :  可变类型 采用 引用 。 有问题

    Python 参数传递：按对象引用传递。

可变对象：函数可以通过引用修改原对象。

不可变对象：不能修改原对象，只能让局部变量重新绑定到新对象。
函数内部给参数重新赋值，不会改变外部变量的绑定；如果对可变对象进行原地修改，外部可以看到变化。
"""

def swap(ls):
    ls[0], ls[1] = ls[1], ls[0]


swap.name = 1
# 定义一个列表
ls = [5, 10]

# 使用 swap 函数 实现 交换
swap(ls)

# 输出列表中的数据
print(ls)
print(swap.__dict__)