"""
整数的表示形式有 4种 

    1.  二进制表示法 :  由  0 和 1 组成的数字 、且 以 0b 开头 
    
    2.  八进制表示法 :  由 0 ~ 7 组成的数字 、且 以  0o 开头 
    
    3.  十进制表示法 :  由 0 ~ 9 组成的数字 
    
    4.  十六进制表示法 : 由 0 ~ 9、 a ~ f 组成、 且以 0x 开头 
 
 
"""

# 使用 二进制表示法 定义一个数字 
a = 0b101011
# 输出 变量对应的值、打印该数字的 十进制
print(a)

# 定义一个 八进制数字 
b = 0o53

print(b)

c = 109
print(c)

# 定义一个十六进制的数字 
d = 0X2B
print(d)