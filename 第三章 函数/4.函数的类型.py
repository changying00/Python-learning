"""
函数的类型总结

我认为函数可以先按“参数”和“返回值”分成 4 种基础类型：

1. 任务型函数：无参数，无返回值
    特点：不需要外部传数据，也不返回结果，只负责完成一个固定任务。
    例如：打印菜单、显示欢迎信息、播放提示音。

2. 消费型函数：有参数，无返回值
    特点：外部传入数据，函数负责把数据“消费掉”，但是不返回结果。
    例如：打印一个数据、发送短信、保存数据。

3. 生产型函数：无参数，有返回值
    特点：不需要外部传数据，函数自己生成一个结果并返回。
    例如：获取当前时间、生成随机验证码、读取用户输入。

4. 加工型函数：有参数，有返回值
    特点：外部传入数据，函数处理之后返回新的结果。
    例如：求和、计算平方、格式化字符串。

除了这 4 种基础类型，还可以再了解一种常见的高级类型：

5. 高阶函数：参数是函数，或者返回值是函数
    特点：函数可以像普通数据一样传递。
    例如：each(ls, lambda x: print(x)) 中，lambda 函数作为参数传给 each。

简单记忆：
    任务型：我自己干活，不要数据，也不给结果。
    消费型：你给我数据，我帮你处理，但不给结果。
    生产型：你不给我数据，我自己生产一个结果给你。
    加工型：你给我数据，我加工后把结果给你。
    高阶函数：函数里面使用另一个函数。
"""


# 1. 任务型函数：无参数，无返回值
def show_menu():
    print("1. 添加")
    print("2. 删除")
    print("3. 修改")


# 2. 消费型函数：有参数，无返回值
def print_data(data):
    print(data)


# 3. 生产型函数：无参数，有返回值
def get_number():
    return 100


# 4. 加工型函数：有参数，有返回值
def add(a, b):
    return a + b


# 5. 高阶函数：参数是函数
def each(iterable, consumer):
    for v in iterable:
        consumer(v)


show_menu()
print_data("hello")
print(get_number())
print(add(10, 20))
each([23, 56, 22], lambda x: print(x))

