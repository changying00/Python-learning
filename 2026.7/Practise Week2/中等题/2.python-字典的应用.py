#切片！！！！！！！！！！！！！！！！！！！！！
#定义一个字典储存每个省对应的编号
area1 = {
"11":"北京","12":"天津","13":"河北",
"14":"山西","15":"内蒙古","21":"辽宁",
"22":"吉林","23":"黑龙江","31":"上海",
"32":"江苏","33":"浙江","34":"安徽",
"35" :"福建","36":"江西","37":"山东",
"41" :"河南","42":"湖北","43":"湖南",
"44" :"广东","45	":"广西","46	":"	海南",
"50" :"重庆","51	":"四川","52	":"	贵州",
"53" :"云南","54	":"西藏","61	":"	陕西",
"62" :"甘肃","63	":"青海","64	":"	宁夏",
"65" :"新疆"}
# 输入身份证号
id_card = input("请输入身份证号：")
# 获取省份
pro_code = id_card[0:2]
pro = area1[pro_code]
# 获取出生日期
birth = id_card[6:14]
# 转换格式
birth = birth[0:4] + "-" + birth[4:6] + "-" + birth[6:8]
# 获取性别
gender_code = int(id_card[16])
if gender_code % 2 == 1:
    gender = "男"
else:
    gender = "女"
# 输出字典
result = {
    "pro": pro,
    "birth": birth,
    "gender": gender
}
print(result)