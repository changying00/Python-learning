#【字典】有2个列表，第一个数组值为：[黑龙江省,浙江省,江西省,广东省,福建省] 表示每一个省份，
# 第二个列表为：[哈尔滨,杭州,南昌,广州,福州]， 表示对应省份的省会城市。
# 编写一个程序、将上述2个列表 转成一个字典，结果格式为： {黑龙江省: 哈尔滨, 浙江省: 杭州, …}

#定义一个变量ls1，存储列表值

ls1 = ["黑龙江省","浙江省","江西省","广东省","福建省"]

#定义一个变量ls2，存储列表值

ls2 = ["哈尔滨","杭州","南昌","广州","福州"]

# dic1 =dict(zip(ls1,ls2))
# print(dic1)
#

dic1 = {
    province:city
    for province,city in zip(ls1,ls2)
}

