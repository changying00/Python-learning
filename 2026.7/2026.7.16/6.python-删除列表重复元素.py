# 定义一个列表，输入值
ls = [1, 2, 2, 5, 3, 23, 2, 1, 2, 2]
ls1 = []

# 使用集合来存储已经遇到的元素
seen = set()

# 遍历数据
for i in ls:
    if i not in seen:
        # 如果元素不在新列表中，添加到新列表
        ls1.append(i)
        # 将元素标记为已遇到
        seen.add(i)

# 输出结果
print(ls1)