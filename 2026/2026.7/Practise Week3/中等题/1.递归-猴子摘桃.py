#【递归】有一群猴子摘了一堆桃子,他们每天都吃当前桃子的一半且再多吃一个,到了第10天就只余下一个桃子.
# 用多种方法实现求出原来这群猴子共摘了多少个桃子
#定义一个递归count_pice
"""
   10 天   =  1
   9  天   =  (第10天的桃子 + 1) * 2
   8 天    =  (第9天的桃子  + 1) * 2
   7       = (第8天的桃子 + 1 ) * 2
   6       = (第7天的桃子 + 1) * 2
   5       = (第6天的桃子  + 1) * 2
   4       = (第5天的桃子 + 1) * 2
   3       = (第4天的桃子  + 1) * 2
   2       = (第3天的桃子  + 1) * 2
   1 天    =  (第2天的桃子 + 1） * 2
"""
# 定义递归函数
def count_pice(n):
    # 递归终止条件：第10天剩下1个桃子
    if n == 10:
        return 1
    # 根据下一天的桃子数量，反推出今天的桃子数量
    return (count_pice(n + 1) + 1) * 2
# 第1天的桃子数量
print(count_pice(1))

