"""
【Ollama】使用结构化 Prompt 生成短片故事

要求：
1. 使用 RTF 风格书写提示词
2. 包含角色、背景、人物关系、剧情、故事类型、字数限制
3. 模型只能输出故事正文，不允许输出分析过程
"""

import ollama


# 使用结构化 Prompt
prompt = r"""
{
    "任务": "生成一篇短片故事",

    "故事要求": {
        "类型": "科幻悬疑",
        "字数": "800-1000字",

        "角色": [
            {
                "姓名": "林默",
                "身份": "人工智能工程师",
                "性格": "冷静、理性、善于分析"
            },
            {
                "姓名": "艾琳",
                "身份": "神秘数据研究员",
                "性格": "聪明、勇敢、充满秘密"
            }
        ],

        "背景": {
            "时间": "未来2075年",
            "地点": "一座高度智能化城市",
            "世界观": "人工智能已经融入人类生活"
        },

        "剧情": {
            "开端": "主人公发现一段未知人工智能代码",
            "发展": "调查过程中发现隐藏多年的秘密",
            "高潮": "人工智能揭露人类未知历史",
            "结局": "主人公做出改变未来的选择"
        }
    },

    "输出要求": {
        "只输出故事内容": true,
        "禁止输出": [
            "标题",
            "分析",
            "解释",
            "创作说明"
        ]
    }
}
"""
messages = [
    {
        "role": "user",
        "content": prompt
    }
]


stream = ollama.chat(
    model="qwen3.5:0.8b",
    messages=messages,
    think=False,
    stream=True
)


for chunk in stream:
    print(chunk.message.content, end="", flush=True)